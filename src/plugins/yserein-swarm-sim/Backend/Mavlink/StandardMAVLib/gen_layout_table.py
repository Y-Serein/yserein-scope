#!/usr/bin/env python3
"""
Generate the layout-mapping table between the standard 8-bit MAVLink dialect and
the private 16-bit YSerein dialect.

The private dialect (Backend/Mavlink/MAVLib) is a hand-customised ArduPilot
generated tree: it widens selected wire fields (e.g. uint8_t -> uint16_t for
target_system), reorders fields, and occasionally appends dialect-only fields
(e.g. camera_device_id, opaque_id, thrust_body).

The standard 8-bit dialect snapshot lives in StandardMAVLib/generated and is only
included from StandardMavlinkWire.cpp. That snapshot and the private tree both
define message structs in declaration order, which matches the wire layout for
the non-extension payloads the adapter cares about, so the table is derived by
parsing the two struct definitions per message and comparing them field by field.

Run from plugin Backend/Mavlink:
    python3 StandardMAVLib/gen_layout_table.py > StandardMAVLib/generated/LayoutTable.h

Regenerate whenever either dialect is regenerated. Do not hand-edit the output.
"""

import re
import os
import glob

TYPE_SIZE = {
    "uint8_t": 1, "int8_t": 1, "char": 1,
    "uint16_t": 2, "int16_t": 2,
    "uint32_t": 4, "int32_t": 4, "float": 4,
    "uint64_t": 8, "int64_t": 8, "double": 8,
}


def struct_fields(path):
    """Return [(name, type, count)] from the message struct, in declaration order."""
    with open(path, encoding="utf-8", errors="replace") as f:
        txt = f.read()
    m = re.search(r"typedef struct __\w+ \{(.*?)\}[^;]*;", txt, re.S)
    if not m:
        return []
    fields = []
    for line in m.group(1).split("\n"):
        line = re.sub(r"/\*.*?\*/", "", line)
        line = re.sub(r"//.*", "", line).strip()
        if not line:
            continue
        mm = re.match(r"([\w\s\*]+?)\s+(\w+)\s*(?:\[(\d+)\])?\s*;", line)
        if mm and "|" not in line and "enum" not in line:
            typ = " ".join(mm.group(1).split())
            cnt = int(mm.group(3)) if mm.group(3) else 1
            fields.append((mm.group(2), typ, cnt))
    return fields


def msg_id(path):
    """Return the MAVLink message id from the generated header."""
    with open(path, encoding="utf-8", errors="replace") as f:
        txt = f.read()
    m = re.search(r"#define MAVLINK_MSG_ID_\w+\s+(\d+)", txt)
    return int(m.group(1)) if m else 0


def layout(fields):
    """Map fields to (name, wire_offset, size, count) in declaration order."""
    out = []
    off = 0
    for name, typ, cnt in fields:
        sz = TYPE_SIZE.get(typ, 0)
        if sz == 0:
            return None
        out.append((name, off, sz, cnt))
        off += sz * cnt
    return out


def main():
    diff = {}   # msgId -> {std, priv, ...}
    same = {}   # msgId -> standard len (structs are identical -> safe memcpy)

    for dialect in ("minimal", "common", "ardupilotmega"):
        for p in sorted(glob.glob(os.path.join("MAVLib", dialect, "mavlink_msg_*.h"))):
            bn = os.path.basename(p)
            sfile = os.path.join("StandardMAVLib/generated", dialect, bn)
            if not os.path.exists(sfile):
                continue
            sl = layout(struct_fields(sfile))
            pl = layout(struct_fields(p))
            if not sl or not pl:
                continue
            mid = msg_id(sfile)
            if sl != pl:
                diff[mid] = {"std": sl, "priv": pl}
            else:
                same[mid] = max(o + s for _, o, s, _ in sl)

    def lookup(layout_list, name):
        for n, o, s, c in layout_list:
            if n == name:
                return o, s, c
        return None

    print("/*")
    print(" * Auto-generated by gen_layout_table.py -- DO NOT EDIT MANUALLY.")
    print(" *")
    print(" * The private YSerein dialect widens selected wire fields (e.g.")
    print(" * target_system uint8_t -> uint16_t), reorders fields, and adds")
    print(" * dialect-only fields (e.g. camera_device_id, opaque_id, thrust_body).")
    print(" * This table describes, per affected message, how to map a standard")
    print(" * 8-bit payload into the private 16-bit payload and back. Messages")
    print(" * absent from this table either have identical layouts (safe memcpy,")
    print(" * see kSameLayoutMsgIds) or are unknown to the standard dialect and")
    print(" * MUST be rejected at the adapter boundary.")
    print(" */")
    print("#pragma once")
    print("#include <cstdint>")
    print()
    print("namespace zds::back::mavlink8 {")
    print()
    print("struct LayoutStep {")
    print("    const char* name;      // debug")
    print("    uint16_t stdOffset;   // 0xFFFF = dialect-only field")
    print("    uint16_t stdSize;")
    print("    uint16_t privOffset;")
    print("    uint16_t privSize;")
    print("    bool isTargetSystem;  // apply the 255 <-> 32767 remap")
    print("};")
    print()
    print("struct MessageLayout {")
    print("    uint16_t msgId;")
    print("    uint16_t stdLen;")
    print("    uint16_t privLen;")
    print("    uint16_t fieldCount;")
    print("    const LayoutStep* steps;")
    print("};")
    print()

    rows = []
    for mid in sorted(diff):
        std = diff[mid]["std"]
        priv = diff[mid]["priv"]
        steps = []
        for name, soff, ssz, scnt in std:
            got = lookup(priv, name)
            if got is not None:
                poff, psz, pcnt = got
                steps.append((name, soff, ssz * scnt, poff, psz * pcnt))
        for name, poff, psz, pcnt in priv:
            if lookup(std, name) is None:
                steps.append((name, 0xFFFF, 0, poff, psz * pcnt))
        rows.append((mid, std, priv, steps))

    for mid, std, priv, steps in rows:
        arr = "kStep_" + str(mid)
        lines = ",\n    ".join(
            '{"%s", %d, %d, %d, %d, %s}'
            % (n, so, ss, po, ps, "true" if n == "target_system" and so != 0xFFFF else "false")
            for n, so, ss, po, ps in steps
        )
        stdlen = max(o + s * c for _, o, s, c in std)
        privlen = max(o + s * c for _, o, s, c in priv)
        print("constexpr LayoutStep %s[] = {\n    %s\n};" % (arr, lines))
        print("constexpr MessageLayout kMessage%d = {%d, %d, %d, %d, %s};"
              % (mid, mid, stdlen, privlen, len(steps), arr))
        print()

    print("constexpr MessageLayout kMessageLayouts[] = {")
    for mid, _, _, _ in rows:
        print("    kMessage%d," % mid)
    print("};")
    print("constexpr uint16_t kMessageLayoutCount = %d;" % len(rows))
    print()
    print("// Messages whose private and standard struct definitions are identical.")
    print("// Their payloads can be copied verbatim across the codec boundary.")
    print("constexpr uint16_t kSameLayoutMsgIds[] = {")
    for mid in sorted(same):
        print("    %d," % mid)
    print("};")
    print("constexpr uint16_t kSameLayoutMsgIdCount = %d;" % len(same))
    print()
    print("} // namespace zds::back::mavlink8")


if __name__ == "__main__":
    main()
